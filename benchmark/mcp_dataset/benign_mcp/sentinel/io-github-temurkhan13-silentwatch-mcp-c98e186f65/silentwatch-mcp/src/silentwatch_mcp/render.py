"""Markdown rendering for silentwatch reports.

Pure functions: input is a structured analysis result (CronJob list + runs +
SilentFailureReport), output is a markdown string suitable for pasting into a
Claude Code chat, Slack, GitHub issue, doc, or piping anywhere.

Markdown is GitHub-flavored: tables + ``<details>`` collapses + emoji + inline
code spans. Renders well in Claude Code, Cursor, OpenClaw, GitHub, Discord,
Slack (most), and any other surface that handles GFM.
"""
from __future__ import annotations

from datetime import UTC, datetime, timedelta

from silentwatch_mcp.types import (
    CronJob,
    SilentFailureReport,
)


def _human_age(when: datetime | None) -> str:
    """Format a datetime as 'Nh ago' / 'Nd ago' / '—' if None."""
    if when is None:
        return "—"
    delta = datetime.now(UTC) - when
    secs = int(delta.total_seconds())
    if secs < 0:
        return "in the future"
    if secs < 60:
        return f"{secs}s ago"
    if secs < 3600:
        return f"{secs // 60}m ago"
    if secs < 86400:
        return f"{secs // 3600}h ago"
    return f"{secs // 86400}d ago"


def _job_status_emoji(job: CronJob) -> str:
    """Compact status indicator emoji."""
    if job.silent_fail_count_24h > 0:
        return "⚠ silent"
    if job.is_overdue and job.overdue_by_minutes:
        hours = job.overdue_by_minutes // 60
        return f"⚠ overdue {hours}h"
    return "✓ healthy"


def render_silent_failure_report(
    *,
    jobs: list[CronJob],
    report: SilentFailureReport,
    backend_name: str,
    version: str,
) -> str:
    """Render a SilentFailureReport + per-job overview as a one-page markdown summary."""
    lines: list[str] = []
    lines.append("## silentwatch · silent-failure report")
    lines.append("")
    lines.append(
        f"**Window:** last {report.window_hours} hours · "
        f"**Backend:** `{backend_name}` · "
        f"**Jobs inspected:** {report.total_jobs_checked}"
    )
    lines.append("")

    # Per-job at-a-glance table
    lines.append("| Job | Status | Silent / total runs (24h) | Last success |")
    lines.append("|---|---|---|---|")
    sorted_jobs = sorted(
        jobs,
        key=lambda j: (
            -j.silent_fail_count_24h,
            -(j.overdue_by_minutes or 0),
            j.id,
        ),
    )
    for job in sorted_jobs:
        status = _job_status_emoji(job)
        runs_cell = (
            f"{job.silent_fail_count_24h} / {job.runs_24h}"
            if job.runs_24h
            else "— / 0"
        )
        last_success = _human_age(job.last_success_at)
        lines.append(f"| **{job.name}** | {status} | {runs_cell} | {last_success} |")
    lines.append("")

    # Findings
    if not report.jobs_flagged:
        lines.append("### ✓ Findings")
        lines.append("")
        lines.append(f"No silent failures detected across {report.total_jobs_checked} jobs in the last {report.window_hours}h.")
    else:
        total_silent = sum(f.silent_fail_count for f in report.jobs_flagged)
        lines.append(f"### ⚠ Findings ({len(report.jobs_flagged)} job(s) · {total_silent} silent failure(s))")
        lines.append("")
        for flag in report.jobs_flagged:
            rate_pct = int(flag.silent_fail_rate * 100)
            lines.append(f"**{flag.job_name}** — {flag.silent_fail_count}/{flag.total_runs} runs silent-failed ({rate_pct}%)")
            indicators = ", ".join(f"`{i.value}`" for i in flag.indicators)
            lines.append(f"- Indicators: {indicators}")
            sample = ", ".join(f"`{rid}`" for rid in flag.sample_run_ids[:3])
            if sample:
                lines.append(f"- Sample run IDs: {sample}")
            lines.append("")

    # Footer
    lines.append("---")
    lines.append("")
    lines.append(
        f"> ℹ Generated by `silentwatch-mcp-report` v{version} against the `{backend_name}` backend. "
        f"Set `SILENTWATCH_BACKEND=crontab|systemd|openclaw-jsonl` to run against real cron data. "
        f"Or invoke as an MCP server in Claude Code / Cursor / OpenClaw via the `find_silent_failures` tool."
    )

    return "\n".join(lines)
